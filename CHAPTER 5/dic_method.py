marks = {
    "Ayushi": 95,
    "Aditya": 85,
    "Suraj": 90,
}

print(marks.items()) #will give us the key-value pairs in tuple form of the dictionary
print(marks.keys()) #will give us the keys of the dictionary
print(marks.values()) #will give us the values of the dictionary
print(marks.update({"Priya": 88})) #will update the dictionary by adding the key "Priya" with value 88