#Arthmatic Operators
a = 7
b = 8
c = a + b
print(c)

#Assignment Operators
x = 5
x += 3 # equivalent to x = x + 3
print(x)
a = 8-3
print(a)

#comparison operators 
p = 5
q = 10
print(p > q) # False
print(p < q) # True

#logical operators
m = True
n = False
print(m and n) # False
print(m or n) # True
print(not m) # False
